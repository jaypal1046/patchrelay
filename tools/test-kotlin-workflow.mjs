import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {dirname, join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {loadBaseline, readJson, fingerprint, checkNative, checkFunctions, sha256, verifiedEnvelope} from '../cli/src/project.mjs';
import {verifySimpleProgram} from './test-compose.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const [selected, patchDirectory] = process.argv.slice(2);
assert.ok(selected && patchDirectory, 'Usage: node tools/test-kotlin-workflow.mjs BASELINE_JSON PATCH_DIRECTORY');
const baselineFile = resolve(selected);
const baseline = loadBaseline(baselineFile);
const settings = readJson(join(root, 'patchrelay.config.json'));
const runtime = readJson(join(root, settings.runtimeFile));
checkNative(baseline.nativeFiles, fingerprint(root, runtime.nativeInputs, runtime.textExtensions));
checkFunctions(baseline.functionContract, readJson(join(root, settings.functionContractFile)));
const program = readFileSync(resolve(patchDirectory, 'screens.js'));
const manifest = verifiedEnvelope(readFileSync(resolve(patchDirectory, 'patch.json')), readFileSync(join(root, settings.publicKeyFile)));
assert.equal(manifest.appId, baseline.appId);
assert.equal(manifest.baseVersion, baseline.baseVersion);
assert.equal(manifest.hostSha256, baseline.hostSha256);
assert.deepEqual(manifest.screenIds, baseline.screenIds);
assert.equal(manifest.sha256, sha256(program));
assert.ok(manifest.version > 0 && program.length <= 2 * 1024 * 1024);
const bundled = readFileSync(join(dirname(baselineFile), 'baseline-screen.js'));
assert.equal(sha256(bundled), baseline.programSha256);
const snapshot = await verifySimpleProgram(bundled, 'baseline');
await verifySimpleProgram(program, 'patch', snapshot);
assert.equal(sha256(readFileSync(join(root, settings.baselineAsset))), baseline.programSha256);
console.log('PASS: pinned-key signature, artifact/base compatibility, immutable v1 bundle, all v2 pages/new Offers page, patched rewards and cross-program state restoration.');
